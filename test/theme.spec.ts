import { expect, test } from '@playwright/test'

test('theme follows the system initially and remembers an explicit choice across pages and reloads', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('html')).toHaveCSS('color-scheme', 'dark')
  await expect(page.locator('.stat').first()).toHaveCSS('background-color', 'rgb(29, 40, 33)')
  const toggle = page.getByRole('button', { name: 'Switch to light theme' })
  await toggle.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Switch to dark theme' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('link', { name: 'Reading guide' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Switch to light theme' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(errors).toEqual([])
})

test('mobile practice supports both themes without losing answers and keeps dark results readable', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await page.getByRole('link', { name: 'Practice Reading to Apply a Diagram' }).click()
  await page.getByRole('button', { name: 'Begin test' }).click()
  await expect(page.locator('.flyer')).toHaveCSS('background-color', 'rgb(48, 38, 30)')
  const answer = page.getByRole('combobox', { name: 'Question 1', exact: true })
  await answer.click()
  await expect(page.getByRole('listbox')).toHaveCSS('background-color', 'rgb(29, 40, 33)')
  await page.getByRole('listbox').getByRole('option').nth(2).click()
  await expect(page.locator('#answer-count')).toHaveText('1 of 8 answered')
  const chosen = await answer.textContent()
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await expect(page.locator('.flyer')).toHaveCSS('background-color', 'rgb(255, 248, 233)')
  await expect(answer).toHaveText(chosen!)
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await page.reload()
  await expect(answer).toHaveText(chosen!)
  await expect(page.getByRole('button', { name: 'Switch to light theme' })).toBeVisible()
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  }
  await page.getByRole('button', { name: 'Finish test' }).click()
  await expect(page.getByRole('dialog')).toHaveCSS('background-color', 'rgb(29, 40, 33)')
  await page.getByRole('button', { name: 'Submit test' }).click()
  await expect(page.locator('.score-card')).toContainText('1 / 8')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('.review-part')).toHaveCSS('background-color', 'rgb(29, 40, 33)')
})

test('theme still switches when browser storage is unavailable', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.addInitScript(() => {
    Object.defineProperty(window, 'localStorage', { get() { throw new Error('Storage unavailable') } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})
